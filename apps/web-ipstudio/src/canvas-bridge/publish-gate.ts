// ─────────────────────────────────────────────────────────────────────────────
// 发布之前先把画布存上（v0.179）。
//
// 为什么必须有这一道：**发布读的是库里那份文档**（服务端 `IpPublishService` →
// `projects.readDoc`），而发布弹窗里能选什么、缩略图长什么样，全来自内存里的画布。
// 自动保存有 900ms 防抖 —— 刚出好一张图就点发布，服务端看到的还是上一版：
//   · 好一点的结果：404「画布上找不到节点」/ 400「这张还没出图，先生成再发布」；
//   · 坏一点的结果：把**上一张图**当主形象登记进资产库，而用户在弹窗里看的是新图。
//     这种最难查 —— 界面和资产库对不上，两边都没有报错。
//
// 存不上（网络故障 / 撞上别处的编辑）就**不发布**，把原因说清楚。
// 刻意不给 publish 加「把 doc 一起带上」的参数：那等于绕开乐观并发闸，
// 冲突时会覆盖别处的编辑（画布是整存整取的，覆盖掉的是那边一整份工作）。
// ─────────────────────────────────────────────────────────────────────────────

import type { SaveOutcome } from "./project-sync";

export async function publishWithLatestDoc<T>(
  saveNow: () => Promise<SaveOutcome>,
  publish: () => Promise<T>,
): Promise<T> {
  const outcome = await saveNow();
  if (outcome === "conflict") {
    throw new Error("这张画布在别处被改过了。刷新页面看到最新内容之后再发布。");
  }
  if (outcome === "failed") {
    throw new Error("画布还没保存上，发布会用到服务端上的旧内容。先点顶栏的「重试保存」，成功之后再发布。");
  }
  return publish();
}
