import { describe, expect, it } from "vitest";
import { sceneScriptLayers, sceneVideoPrompt } from "./scene-script-layers";

// 2026-11-09 线上 terra 按第 6 轮编导提示词写的一份（马记大排档，缩短了镜头数）。
const SCRIPT = [
  "一、剧情概述",
  "面向喜欢探店的观众，以热气腾腾的牛杂煲（图1）和第一口反应抓住注意力。",
  "",
  "二、素材与职责",
  "门店照片 1（图1）：牛杂煲参考，用于开场和夹起牛杂的特写。",
  "出镜人物（图2）：人物长相、发型和穿着参考，用于全片人物出镜。",
  "声音样本：口播声音参考，全片由同一人说话。",
  "",
  "三、主体与关系",
  "阿岚（图2）：短黑发，戴圆框眼镜；气色好，皮肤干净有光泽。",
  "",
  "四、场景与视觉设定",
  "画面风格：竖屏9：16，手机探店实拍质感。",
  "",
  "五、镜头时间轴",
  "第1镜（0–4秒）这一镜的作用：用热气和牛杂截停。",
  "摄影：近景低机位，推向筷子夹起的牛杂。",
  "阿岚说：「马记大排档这锅，看着就想先吃一口。」",
  "",
  "第2镜（4–8秒）这一镜的作用：拍清第一口和真实反应。",
  "表演：阿岚（图2）带着期待咬下一口，满意地点头。",
  "阿岚在画外说：「牛杂软糯咸香，越嚼越有味。」",
  "",
  "六、全片保持与禁止",
  "始终保持：阿岚（图2）的人脸、短发和服装一致。",
  "始终禁止：字幕、水印、人脸变形、多出来的人。",
].join("\n");

describe("sceneScriptLayers", () => {
  it("只发和画面有关的部分：素材压成一行对照，去掉剧情概述、每镜的作用和「始终保持」，禁止项放最后", () => {
    const prompt = sceneScriptLayers(SCRIPT)!.prompt;
    expect(prompt).toBe([
      "素材：图1 牛杂煲参考；图2 人物长相、发型和穿着参考；声音样本 口播声音参考",
      "",
      "阿岚（图2）：短黑发，戴圆框眼镜；气色好，皮肤干净有光泽。",
      "",
      "画面风格：竖屏9：16，手机探店实拍质感。",
      "",
      "第1镜（0–4秒）",
      "摄影：近景低机位，推向筷子夹起的牛杂。",
      "阿岚说：「马记大排档这锅，看着就想先吃一口。」",
      "",
      "第2镜（4–8秒）",
      "表演：阿岚（图2）带着期待咬下一口，满意地点头。",
      "阿岚在画外说：「牛杂软糯咸香，越嚼越有味。」",
      "",
      "画面中不要出现：字幕、水印、人脸变形、多出来的人。",
    ].join("\n"));
  });

  it("标出编辑框里不发出去的位置：剧情概述整段（标题行带「仅参考」）、每镜的作用、「始终保持」", () => {
    const lines = SCRIPT.split("\n");
    const hidden = sceneScriptLayers(SCRIPT)!.hidden;
    const text = hidden.map(h => lines[h.line].slice(h.from, h.to));
    expect(text).toEqual([
      "一、剧情概述",
      "面向喜欢探店的观众，以热气腾腾的牛杂煲（图1）和第一口反应抓住注意力。",
      "这一镜的作用：用热气和牛杂截停。",
      "这一镜的作用：拍清第一口和真实反应。",
      "始终保持：阿岚（图2）的人脸、短发和服装一致。",
    ]);
    expect(hidden.filter(h => h.tag).map(h => h.line)).toEqual([0]);
  });

  it("标题写法不同也认：Markdown 标题、阿拉伯数字、冒号后接正文、全角数字", () => {
    const script = [
      "### 1. 剧情概述：一句话讲清楚。",
      "**2. 素材与职责**",
      "「门店门头.jpg」是场景参考，用在开场门口那一镜。",
      "5、镜头时间轴：",
      "第１镜（０–４秒）这一镜的作用：截停",
      "博主说：「到了！」",
    ].join("\n");
    const layers = sceneScriptLayers(script)!;
    expect(layers.prompt).toBe("素材：门店门头.jpg 场景参考\n\n第1镜（0–4秒）\n博主说：「到了！」");
    expect(layers.hidden[0]).toEqual({ line: 0, from: 0, to: script.split("\n")[0].length, tag: true });
  });

  it("认不出六段结构就原样发：用户贴进来的别家提示词一个字都不删", () => {
    const pasted = "【画面风格】真实写实，高级电影质感\n0-3秒：女孩推门进店，一脸不服气。{这家真有那么神？}\n禁止：字幕、水印";
    expect(sceneScriptLayers(pasted)).toBeUndefined();
    expect(sceneVideoPrompt(pasted)).toBe(pasted);
    // 有镜头段标题但里面没有「第N镜」也不挑：宁可不删，不删错。
    expect(sceneScriptLayers("一、剧情概述：试吃\n五、镜头时间轴：先拍门头，再拍菜")).toBeUndefined();
  });
});
